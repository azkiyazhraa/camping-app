        @if (session('success') || session('error') || session('warning') || session('info'))

            document.addEventListener('DOMContentLoaded', function() {
                @if (session('success'))
                    swal("Success!", "{{ session('success') }}", "success");
                @elseif (session('error'))
                    swal("Error!", "{{ session('error') }}", "error");
                @elseif (session('warning'))
                    swal("Warning!", "{{ session('warning') }}", "warning");
                @elseif (session('info'))
                    swal("Info", "{{ session('info') }}", "info");
                @endif
            });
        @endif

        document.addEventListener('DOMContentLoaded', function() {
            document.querySelectorAll('.btn-delete').forEach(button => {
                button.addEventListener('click', function(e) {
                    e.preventDefault();
                    const form = this.closest('form');
                    swal({
                        title: "Are you sure?",
                        text: "This action cannot be undone!",
                        icon: "warning",
                        buttons: [true, "Yes, delete it!"],
                        dangerMode: true,
                    }).then((willDelete) => {
                        if (willDelete) {
                            form.submit();
                        }
                    });
                });
            });
        });

        document.addEventListener('DOMContentLoaded', function() {
            document.querySelectorAll('.btn-edit').forEach(button => {
                button.addEventListener('click', function() {
                    const id = this.getAttribute('data-id');
                    const name = this.getAttribute('data-name');
                    const stock = this.getAttribute('data-stock');
                    const rental_price = this.getAttribute('data-rental_price');
                    const description = this.getAttribute('data-description');
                    const image = this.getAttribute('data-image');

                    // Set form action
                    const form = document.getElementById('editToolForm');
                    form.action = `/tools/${id}`;

                    // Isi data ke form
                    document.getElementById('editToolName').value = name;
                    document.getElementById('editToolStock').value = stock;
                    document.getElementById('editToolRentalPrice').value = rental_price;
                    document.getElementById('editToolDescription').value = description;
                    document.getElementById('editToolImagePreview').src = image;
                });
            });
        });
    </script>
